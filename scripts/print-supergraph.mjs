#!/usr/bin/env node
/**
 * Composes the federated supergraph offline from each subgraph's SDL (the same
 * composition the gateway runs at start-up) and writes:
 *   docs/supergraph.graphql   – the client-facing API schema
 * Fails (exit 1) on composition errors, so CI catches breaking subgraph changes.
 * Requires `npm run build:services`.
 */
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = fileURLToPath(new URL('..', import.meta.url));
const { composeServices } = require(
  require.resolve('@apollo/composition', { paths: [join(root, 'services/gateway')] }),
);
const { parse, printSchema } = require('graphql');

const sdl = (svc) => require(join(root, `services/${svc}/dist/graphql/schema.js`)).typeDefs;
const subgraphs = [
  {
    name: 'identity',
    url: 'local://identity',
    typeDefs: parse(
      require(join(root, 'services/gateway/dist/identity/identity.subgraph.js')).identityTypeDefs,
    ),
  },
  ...['catalog', 'orders', 'payments', 'notifications'].map((name) => ({
    name,
    url: `http://${name}/graphql`,
    typeDefs: parse(sdl(name)),
  })),
];

const result = composeServices(subgraphs);
if (result.errors?.length) {
  console.error(result.errors.map((e) => e.message).join('\n'));
  process.exit(1);
}
const api = printSchema(result.schema.toAPISchema().toGraphQLJSSchema());
writeFileSync(
  join(root, 'docs/supergraph.graphql'),
  `# Generated by scripts/print-supergraph.mjs — do not edit.\n# Client-facing schema composed from: ${subgraphs.map((s) => s.name).join(', ')}\n\n${api}\n`,
);
console.log(
  `composed ${subgraphs.length} subgraphs -> docs/supergraph.graphql (${api.split('\n').length} lines)`,
);
